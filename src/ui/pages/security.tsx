import type { FC } from "hono/jsx";
import type { PasskeySummary } from "../../storage/webauthn";
import { MAX_PASSKEY_NAME_LENGTH } from "../../storage/webauthn";
import { formatDate } from "../format";
import { Layout } from "../layout";
import { WEBAUTHN_CLIENT_SCRIPT } from "../webauthn-client";
import type { SettingsNotice, SettingsUser } from "./settings";

/**
 * `/settings/security` — passkeys (the second factor) and recovery codes (#256).
 *
 * Rename, remove and "new recovery codes" are plain forms. Adding a passkey is
 * the one action that needs JavaScript: WebAuthn is a browser API with no form
 * equivalent. The script calls the JSON API and, for the first passkey, shows
 * the recovery codes the response carries.
 */
interface SecurityPageProps {
  user: SettingsUser;
  passkeys: PasskeySummary[];
  recoveryCodesRemaining: number;
  /** Orgs whose "require a second factor" policy this session does not meet.
   * Only those orgs' resources are affected. */
  requiringOrgs: string[];
  /** Whether this session may add or remove passkeys right now (fresh, and
   * second-factor-verified once the account has a passkey). */
  canChange: boolean;
  /** Recovery codes just generated by a form POST — shown once. */
  freshRecoveryCodes?: string[];
  notice?: SettingsNotice;
  nonce: string;
}

const PAGE_SCRIPT = `(function () {
  var form = document.getElementById("add-passkey-form");
  var status = document.getElementById("add-passkey-status");
  var codesCard = document.getElementById("new-recovery-codes");
  var codesList = document.getElementById("new-recovery-codes-list");
  if (!form || !status) return;
  function say(msg) { status.textContent = msg; }
  if (!window.StratumPasskey || !window.StratumPasskey.supported) {
    form.querySelector("button").disabled = true;
    say("This browser does not support passkeys.");
    return;
  }
  form.addEventListener("submit", async function (ev) {
    ev.preventDefault();
    var button = form.querySelector("button");
    button.disabled = true;
    say("Follow your browser's prompt…");
    try {
      var optRes = await fetch("/api/users/me/passkeys/registration/options", {
        method: "POST",
        credentials: "same-origin",
      });
      var opts = await optRes.json();
      if (!optRes.ok) throw opts;
      var response = await window.StratumPasskey.create(opts);
      var name = form.querySelector("input[name=name]").value;
      var verRes = await fetch("/api/users/me/passkeys/registration/verify", {
        method: "POST",
        credentials: "same-origin",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ name: name, response: response }),
      });
      var result = await verRes.json();
      if (!verRes.ok) throw result;
      if (result.recoveryCodes && codesCard && codesList) {
        codesList.textContent = "";
        result.recoveryCodes.forEach(function (code) {
          var li = document.createElement("li");
          li.textContent = code;
          codesList.appendChild(li);
        });
        codesCard.hidden = false;
        say("Passkey added. Save your recovery codes, then reload this page.");
        return;
      }
      window.location.assign("/settings/security?notice=passkey-added");
    } catch (e) {
      say((e && e.error) || "The passkey was not added. Try again.");
      button.disabled = false;
    }
  });
})();`;

const RecoveryCodeList: FC<{ id?: string; codes: string[] }> = ({ id, codes }) => (
  <ul class="settings-help recovery-codes" {...(id !== undefined ? { id } : {})}>
    {codes.map((code) => (
      <li key={code}>
        <code>{code}</code>
      </li>
    ))}
  </ul>
);

export const SecurityPage: FC<SecurityPageProps> = ({
  user,
  passkeys,
  recoveryCodesRemaining,
  requiringOrgs,
  canChange,
  freshRecoveryCodes,
  notice,
  nonce,
}) => (
  <Layout title="Security" user={user} active="settings">
    <div class="page-header">
      <h1>Security</h1>
      <div class="header-actions">
        <a class="btn" href="/settings">
          Settings
        </a>
      </div>
    </div>

    {requiringOrgs.length > 0 && (
      <div class="card card-error">
        <p class="settings-help settings-notice">
          {requiringOrgs.length === 1 ? "The organization " : "The organizations "}
          <strong>{requiringOrgs.join(", ")}</strong>{" "}
          {requiringOrgs.length === 1 ? "requires" : "require"} a second factor for{" "}
          {requiringOrgs.length === 1 ? "its" : "their"} projects and settings.{" "}
          {passkeys.length === 0
            ? "Add a passkey to reach them."
            : "Sign out and sign in again with your passkey to reach them."}{" "}
          Your own projects and other organizations are not affected.
        </p>
      </div>
    )}

    {notice && (
      <div class={`card ${notice.kind === "error" ? "card-error" : "card-success"}`}>
        <p class="settings-help settings-notice">{notice.message}</p>
      </div>
    )}

    {freshRecoveryCodes !== undefined && (
      <div class="card settings-token-reveal">
        <h2>Your new recovery codes</h2>
        <p class="settings-help">
          Store these somewhere safe — they are shown only once. Each code signs you in once if you
          lose your passkey. Your previous codes no longer work.
        </p>
        <RecoveryCodeList codes={freshRecoveryCodes} />
      </div>
    )}

    <div class="card settings-token-reveal" id="new-recovery-codes" hidden>
      <h2>Your recovery codes</h2>
      <p class="settings-help">
        Store these somewhere safe — they are shown only once. Each code signs you in once if you
        lose your passkey.
      </p>
      <ul class="settings-help recovery-codes" id="new-recovery-codes-list" />
    </div>

    <div class="card" id="passkeys">
      <h2>Passkeys</h2>
      <p class="settings-help">
        A passkey is a second factor: after you sign in with email, GitHub, Google or SSO, Stratum
        asks for it before your session starts. API tokens, agent tokens and connected apps are not
        affected.
      </p>
      {passkeys.length === 0 ? (
        <p class="settings-help">You have no passkeys yet.</p>
      ) : (
        <div class="table-scroll">
          <table class="table">
            <thead>
              <tr>
                <th>Name</th>
                <th>Added</th>
                <th>Last used</th>
                <th />
              </tr>
            </thead>
            <tbody>
              {passkeys.map((p) => (
                <tr key={p.id}>
                  <td>
                    <form
                      method="post"
                      action={`/settings/security/passkeys/${p.id}/rename`}
                      class="settings-inline-form"
                    >
                      <input
                        name="name"
                        value={p.name}
                        maxlength={MAX_PASSKEY_NAME_LENGTH}
                        aria-label="Passkey name"
                        required
                      />
                      <button type="submit" class="btn btn-small">
                        Rename
                      </button>
                    </form>
                  </td>
                  <td>{formatDate(p.createdAt)}</td>
                  <td>{p.lastUsedAt ? formatDate(p.lastUsedAt) : "Never"}</td>
                  <td>
                    <form method="post" action={`/settings/security/passkeys/${p.id}/delete`}>
                      <button type="submit" class="btn btn-small btn-danger" disabled={!canChange}>
                        Remove
                      </button>
                    </form>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      )}

      {canChange ? (
        <form id="add-passkey-form" class="settings-form">
          <label>
            Name for the new passkey
            <input
              name="name"
              placeholder="e.g. MacBook Touch ID"
              maxlength={MAX_PASSKEY_NAME_LENGTH}
            />
          </label>
          <button type="submit" class="btn btn-primary">
            Add passkey
          </button>
          <p id="add-passkey-status" class="settings-help" aria-live="polite">
            <noscript>Adding a passkey needs JavaScript.</noscript>
          </p>
        </form>
      ) : (
        <p class="settings-help">
          To add or remove a passkey, sign out and sign in again
          {passkeys.length > 0 ? " with your passkey" : ""} — changes need a sign-in from the last
          15 minutes.
        </p>
      )}
    </div>

    {passkeys.length > 0 && (
      <div class="card" id="recovery">
        <h2>Recovery codes</h2>
        <p class="settings-help">
          {recoveryCodesRemaining} unused recovery code{recoveryCodesRemaining === 1 ? "" : "s"}{" "}
          left. Generating new codes invalidates the old ones.
        </p>
        <form method="post" action="/settings/security/recovery-codes">
          <button type="submit" class="btn" disabled={!canChange}>
            Generate new recovery codes
          </button>
        </form>
      </div>
    )}

    <script
      nonce={nonce}
      dangerouslySetInnerHTML={{ __html: WEBAUTHN_CLIENT_SCRIPT + PAGE_SCRIPT }}
    />
  </Layout>
);
